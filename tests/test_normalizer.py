@pytest.mark.parametrize("raw, expected", CASES, ids=[c[0][:40] for c in CASES])
def test_normalize(raw, expected):
    assert normalize_merchant(raw) == expected


def test_case_count_and_edge_inputs():
    assert len(CASES) >= 60
    assert normalize_merchant("") == "" and normalize_merchant("   ") == ""
    assert normalize_merchant("12345678901234") != ""  # all-noise input falls back, never empty
    assert len(normalize_merchant("X" * 500)) <= 80
